"""Нормализация телефонных номеров к формату 7XXXXXXXXXX."""
from __future__ import annotations

import re


def normalize_phone(raw: str | None) -> str | None:
    """Приводит номер к формату 7XXXXXXXXXX (11 цифр, начинается с 7).

    - удаляет всё, кроме цифр;
    - ведущую 8 заменяет на 7;
    - к 10-значному номеру добавляет 7 спереди.

    Возвращает None, если из строки не получился валидный 11-значный номер,
    начинающийся на 7.
    """
    if not raw:
        return None

    digits = re.sub(r"\D", "", raw)

    if len(digits) == 11 and digits.startswith("8"):
        digits = "7" + digits[1:]
    elif len(digits) == 10:
        digits = "7" + digits

    if len(digits) == 11 and digits.startswith("7"):
        return digits
    return None


# Телефонный паттерн: опциональный «+», затем 10–11 цифр, между которыми могут
# стоять разделители (пробел, дефис, скобки). Ловит «+79114053330», «89114053330»,
# «8 (911) 405-33-30», а также номер внутри фразы. Порог в 10 цифр не задевает
# номера домов/индексы (они короче или разделены буквами).
_PHONE_RE = re.compile(r"\+?\d(?:[\s\-()]*\d){9,10}")

_PHONE_MASK = "[номер скрыт]"


def strip_phones(text: str | None) -> str | None:
    """Маскирует любые телефонные паттерны в тексте — защита от утечки в карточке.

    Применять ко ВСЕМУ, что идёт в текст Telegram-карточки администратору
    (имя/адрес/комментарий): телефон клиента не должен попасть в сообщение.
    None и пустую строку возвращает как есть.
    """
    if not text:
        return text
    return _PHONE_RE.sub(_PHONE_MASK, text)


def mask_phone(raw: str | None) -> str:
    """Частично скрывает номер для записи в лог: 79991234567 -> 7***4567.

    Нужна там, где номер сотрудника всё же приходится логировать (разбор входящих
    событий Mango): по хвосту из 4 цифр человек узнаёт свой номер и мы можем
    отлаживать сопоставление АОН, но полный номер в логи не попадает.
    Телефон КЛИЕНТА не логируется вообще — ни в каком виде.
    """
    if not raw:
        return "—"
    digits = re.sub(r"\D", "", raw)
    if len(digits) < 5:
        return "***"
    return f"{digits[0]}***{digits[-4:]}"
